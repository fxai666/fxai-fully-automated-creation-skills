"""把 assets/models.json + assets/nodes.json 编译成一段自包含的远端 bash 脚本。

设计要点：
- 幂等：已存在且体积达标的文件直接跳过，中断后重跑可用 curl -C - 续上。
- 下载走探测过的验证直链 → 魔搭 → HF，默认不开备用源；需调顺序才显式设 XGY_SRC_ORDER。
- 重命名落位：仓库内文件名与目标名不同时，先下到 .otai/ 再 mv 成目标名。
- 体积校验：先 HEAD 拿 Content-Length 对账；拿不到就退回 min_bytes 下限。
- 装节点：git clone --depth 1，已存在则 git pull --ff-only，再按 requirements.txt 装依赖。
"""
from __future__ import annotations

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ASSETS = os.path.join(os.path.dirname(HERE), "assets")


def load(name):
    with open(os.path.join(ASSETS, name), encoding="utf-8") as f:
        return json.load(f)


def human(n: float) -> str:
    for u in ("B", "K", "M", "G", "T"):
        if n < 1024:
            return f"{n:.1f}{u}"
        n /= 1024
    return f"{n:.1f}P"


def src_order(m):
    """这个模型的下载源顺序（第 13 列），来自 probe_sources.py 的探测结果。

    格式 `<源名>:<能否续传>`。默认就是**探测时认定的那一个源**，不排队伍、不挨个换源
    ——每次换源都可能撞上「不支持续传的源把进度清零」，所以既然地址已经探好了，
    就认这一个地址反复续，别再试别的（2026-10-03 被换源坑掉三次之后定的规矩）。
    """
    cs = m.get("sources") or []
    if cs:
        return ",".join(f"{c['src']}:{1 if c.get('range') else 0}" for c in cs)
    src = m.get("source")
    if src:
        return src
    return "probe,ms,hf"


def pick_models(group, include_optional, variant, only=None, skip=None, set_dir=None):
    mf = load("models.json")
    only = set(only or [])
    skip = set(skip or [])
    set_dir = set_dir or {}
    out = []
    for m in mf["models"]:
        if only:
            if m["id"] not in only:
                continue
        elif m["group"] not in group:
            continue
        if m["id"] in skip:
            continue
        if m.get("optional") and not include_optional:
            continue
        m = dict(m)
        if m.get("variants"):
            v = (m.get("variants") or {}).get(variant)
            if v:
                m["path"] = v["path"]
                m["min_bytes"] = v.get("min_bytes", m["min_bytes"])
                # variant 真换了文件才作废探测结果（地址/大小是照着另一条 path 探的，
                # 留着会去拉一个「存在但内容不对」的文件）。path 没变就原样保留。
                if v.get("path", m["path"]) != m["path"] or v.get("min_bytes", m["min_bytes"]) != m["min_bytes"]:
                    for k in ("source", "source_url", "source_bytes", "sources"):
                        m.pop(k, None)
        if m["id"] in set_dir:
            m["target_dir"] = set_dir[m["id"]]
        out.append(m)
    return mf, out


def node_list(required_only=True):
    nf = load("nodes.json")
    return nf, [n for n in nf["nodes"] if n.get("required") or not required_only]


def render(groups, include_optional, variant, only=None, skip=None, set_dir=None,
           required_only=True, do_nodes=True, do_models=True, comfy_dir="",
           upgrade_comfy=False, parallel=1):
    mf, models = pick_models(groups, include_optional, variant, only, skip, set_dir)
    nf, nodes = node_list(required_only)
    total = sum(m["min_bytes"] for m in models if not m.get("optional"))

    L = []
    a = L.append

    a("#!/usr/bin/env bash")
    a("# ============================================================")
    a("#  OneThingAI · 凤希技能包一键部署")
    a("#  由 WorkBuddy 技能 fxai-xiangongyun-deploy 生成")
