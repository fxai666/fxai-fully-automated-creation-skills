        a("install_node() {")
        a('  local repo="$1" dir="$2" i')
        a('  local target="$CN_DIR/$dir"')
        a('  if [ -d "$target/.git" ]; then')
        a('    log "更新 $dir ..."')
        a('    git -C "$target" pull --ff-only >/dev/null 2>&1 || log "  pull 失败，保留现有版本（不致命）"')
        a("  else")
        a('    rm -rf "$target"')
        a('    for i in 1 2 3; do')
        a('      log "克隆 $dir（第 $i 次）..."')
