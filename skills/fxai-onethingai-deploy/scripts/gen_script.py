    a('  VRAM=$(nvidia-smi --query-gpu=memory.total --format=csv,noheader,nounits 2>/dev/null | head -n1 | tr -d " ")')
    a('  [ -n "$VRAM" ] && log "GPU 显存 ${VRAM} MiB（单个模型超过这个数就要靠节点的分块/卸载，24G 卡建议用 --variant pruned 之类的小档）"')
    a("fi")
    a('log "本次预计新增 $((NEED/1073741824)) GB（含 20% 余量），目标盘可用 $((AVAIL/1073741824)) GB"')
    a('df -h "$MODELS_DIR" | tail -n1 | sed "s/^/  /"')
    a('if [ "$AVAIL" -lt "$NEED" ]; then')
