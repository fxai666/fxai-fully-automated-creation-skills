    a(f'MIRROR2="${{XGY_MIRROR2:-{mf.get("mirror2", "")}}}"')
    _rs = mf.get("resume") or {}
    a(f'RESUME_MS="{1 if _rs.get("ms", 1) else 0}"')
    a(f'RESUME_HF="{1 if _rs.get("hf", 0) else 0}"')
    a(f'RESUME_MIRROR="{1 if _rs.get("mirror", 0) else 0}"')
    a(f'COMFY_DIR="${{XGY_COMFY_DIR:-{comfy_dir}}}"')
    a(f'UPGRADE_COMFY="{1 if upgrade_comfy else 0}"')
    a(f'PARALLEL="{max(1, int(parallel))}"')
    a('RC_FILE=/tmp/otai_deploy.rc')
    a('BAD_FILE=/tmp/otai_deploy.bad')
    a('OK_FILE=/tmp/otai_deploy.ok')
    a('SKIP_FILE=/tmp/otai_deploy.skip')
    a("rm -f \"$BAD_FILE\" \"$OK_FILE\" \"$SKIP_FILE\"")
    a('echo 0 > "$RC_FILE"')
    a("finish() { rc=$?; echo $rc > \"$RC_FILE\"; }")
    a("trap finish EXIT")
    a("")
    a("ts() { date '+%H:%M:%S'; }")
    a('log() { echo "[$(ts)] $*"; }')
    a('err() { echo "[$(ts)] [ERR] $*" >&2; }')
    a('step() { echo; echo "======== $* ========"; }')
    a('mark() { echo "$2" >> "$1"; }')
    a("")
    a("############################################################")
    a("# 1) 定位 ComfyUI")
    a("############################################################")
    a("detect_comfy() {")
    a('  if [ -n "$COMFY_DIR" ] && [ -d "$COMFY_DIR" ]; then echo "$COMFY_DIR"; return 0; fi')
    a("  local c")
    a("  for c in /root/ComfyUI /root/ComfyUI-* /workspace/ComfyUI /workspace/ComfyUI-* \\")
    a("           /home/*/ComfyUI /root/*/ComfyUI /opt/ComfyUI /data/ComfyUI /data/*/ComfyUI; do")
    a('    [ -d "$c" ] && { echo "$c"; return 0; }')
    a("  done")
    a("  c=$(find / -maxdepth 5 -type d -name custom_nodes -path '*ComfyUI*' 2>/dev/null | head -n1)")
    a('  [ -n "$c" ] && { echo "$(dirname "$c")"; return 0; }')
    a("  return 1")
    a("}")
    a("")
    a("COMFY_DIR=$(detect_comfy || true)")
    a('if [ -z "$COMFY_DIR" ]; then')
    a(f'  log "未找到 ComfyUI，克隆官方仓库到 /root/ComfyUI（需 >= {nf["comfy_min_version"]}，H3 支持起点）"')
    a('  command -v git >/dev/null 2>&1 || { err "没有 git：apt-get update && apt-get install -y git"; }')
    a('  [ -d /root/ComfyUI ] || git clone --depth 1 https://github.com/comfyanonymous/ComfyUI.git /root/ComfyUI')
    a('  COMFY_DIR=/root/ComfyUI')
    a("fi")
    a('log "ComfyUI = $COMFY_DIR"')
    a('MODELS_DIR="$COMFY_DIR/models"')
    a('CN_DIR="$COMFY_DIR/custom_nodes"')
    a('mkdir -p "$MODELS_DIR" "$CN_DIR"')
    a("")
    a("############################################################")
    a("# 1b) ComfyUI 版本")
    a("############################################################")
    a("comfy_version() {")
    a('  tr -d " \\t" < "$COMFY_DIR/comfyui_version.py" 2>/dev/null \\')
    a("    | sed -n 's/^__version__=//p' | head -n1 | tr -d '\"'")
    a("}")
    a('CV=$(comfy_version)')
    a('log "ComfyUI 版本：${CV:-未知}  （本技能包要求 >= ' + nf["comfy_min_version"] + '）"')
    a('CV_MAJ=${CV%%.*}')
    a('CV_MIN=$(echo "${CV:-0.0.0}" | cut -d. -f2)')
    a(f'REQ_MAJ={nf["comfy_min_version"].split(".")[0]}')
    a(f'REQ_MIN={nf["comfy_min_version"].split(".")[1]}')
    a('WANT_MAJ=${REQ_MAJ}')
    a('WANT_MIN=${REQ_MIN}')
    a('if [ -z "${CV_MAJ:-}" ] || [ "${CV_MAJ:-0}" -lt "$WANT_MAJ" ] 2>/dev/null \\')
    a('   || { [ "${CV_MAJ:-0}" -eq "$WANT_MAJ" ] && [ "${CV_MIN:-0}" -lt "$WANT_MIN" ]; }; then')
    a(f'  err "  ⚠ ComfyUI 版本过低（当前 $CV / 需要 {nf["comfy_min_version"]}）。H3 / 千问2.1 / YuE2 相关节点会缺失。加 --upgrade-comfy 可升级。"')
    a("fi")
    a("")
    a('if [ "$UPGRADE_COMFY" = "1" ]; then')
    a('  log "升级 ComfyUI（git pull --ff-only）..."')
    a('  if git -C "$COMFY_DIR" rev-parse --is-inside-work-tree >/dev/null 2>&1; then')
    a('    # 坑 1：工作区脏（有人删过 blueprints/*.json）会让 pull 直接拒绝，先恢复被删的文件。')
    a('    if [ -n "$(git -C "$COMFY_DIR" status --porcelain --untracked-files=no 2>/dev/null)" ]; then')
    a('      log "  工作区有改动，先 checkout 恢复（只动已跟踪文件的删除/修改）"')
    a('      git -C "$COMFY_DIR" status --porcelain --untracked-files=no 2>/dev/null | head -5 | sed "s/^/    /"')
    a('      git -C "$COMFY_DIR" checkout -- . 2>&1 | tail -n 2 | sed "s/^/    /"')
    a("    fi")
    a('    # 坑 2（真正的原因）：--depth N 的 shallow clone 算不出 merge-base，')
    a('    #     git 会误判成历史分叉，pull --ff-only 必然报 "Not possible to fast-forward"。')
    a('    #     shallow clone 报「领先 N 提交」= 缺历史，补全历史后 pull。')
    a('    #     解法：先 fetch --unshallow 把历史补全，pull 就正常了。')
    a('    if [ -f "$COMFY_DIR/.git/shallow" ]; then')
    a('      log "  是 shallow clone（深度 $(wc -l < "$COMFY_DIR/.git/shallow" | tr -d " ")），先补全历史 ..."')
    a('      git -C "$COMFY_DIR" fetch --unshallow origin >/dev/null 2>&1 || git -C "$COMFY_DIR" fetch --deepen 3000 origin >/dev/null 2>&1 || true')
    a('      [ -f "$COMFY_DIR/.git/shallow" ] && log "  仍是 shallow（不致命，继续尝试 pull）" || log "  历史已补全 ✓"')
    a("    fi")
    a('    git -C "$COMFY_DIR" pull --ff-only 2>&1 | tail -n 6 | sed "s/^/    /"')
    a("  else")
    a('    log "  不是 git 仓库，跳过升级（不致命）"')
    a("  fi")
    a('  log "升级后版本：$(comfy_version)（需要重启 ComfyUI 才生效）"')
    a("fi")
    a("")
    a("# 找可用的 python 解释器。**必须用跑 ComfyUI 的那个**，系统 python3 往往没 pip 也没 torch。")
    a("# 坑：screen/tmux 的 cmdline 里也含 'python main.py'，pgrep -f 会一起命中，")
    a("#     /proc/<screen_pid>/exe 指向 screen 而不是 python —— 所以必须按 exe 名过滤。")
    a("detect_py() {")
    a("  local c p b")
    a("  # 1) 从正在运行的 ComfyUI 进程反查解释器（最准）")
    a('  for p in $(pgrep -f "main.py" 2>/dev/null); do')
    a('    c=$(readlink -f /proc/$p/exe 2>/dev/null) || continue')
    a('    b=$(basename "$c" 2>/dev/null)')
    a('    case "$b" in python*) ;; *) continue ;; esac')
    a('    [ -x "$c" ] && { echo "$c"; return 0; }')
    a("  done")
    a('  # 2) conda / venv 里带 torch 的解释器')
    a('  for c in /root/miniconda3/envs/*/bin/python /opt/conda/envs/*/bin/python \\')
    a('           /root/anaconda3/envs/*/bin/python "$COMFY_DIR/venv/bin/python" "$COMFY_DIR/.venv/bin/python"; do')
    a('    [ -x "$c" ] || continue')
    a('    [ -d "$(dirname "$(dirname "$c")")/lib/python"*/site-packages/torch ] || continue')
    a('    echo "$c"; return 0')
    a("  done")
    a('  # 3) 兜底：PATH 里的 python3')
    a('  for c in "$(command -v python3)" "$(command -v python)"; do')
    a('    [ -x "$c" ] && { echo "$c"; return 0; }')
    a("  done")
    a("  return 1")
    a("}")
    a("")
    a('PY=$(detect_py || true)')
    a('if [ -z "$PY" ]; then err "找不到 ComfyUI 用的 python 解释器，节点依赖装不上（不致命，可重启 ComfyUI 后手动补）";')
    a('else log "python = $PY ($($PY -V 2>&1))"; fi')
    a('if [ -n "$PY" ] && ! "$PY" -m pip -V >/dev/null 2>&1; then')
    a('  log "  该解释器没有 pip，尝试 ensurepip ..."')
    a('  "$PY" -m ensurepip --upgrade >/dev/null 2>&1 || true')
    a("fi")
    a("")
    a('HAVE_CURL=""; command -v curl >/dev/null 2>&1 && HAVE_CURL=1')
    a('if [ -z "$HAVE_CURL" ]; then')
    a('  err "curl 没有，先装：apt-get update && apt-get install -y curl"')
    a("fi")
    a('log "下载器：curl=${HAVE_CURL:-无}（不用 wget：镜像源不支持 Range 续传）"')
    a("")

    a("############################################################")
    a("# 2) 模型清单（由本地 assets/models.json 编译而来）")
    a("############################################################")
    a("# 格式: id|repo|ms_repo|仓库内路径|目标子目录|落盘文件名|体积下限|可选|分组|说明|直链|真实字节|源顺序")
    a("#")
    a("# 第 11、12 列和第 13 列都是 probe_sources.py **提前探测**的结果：")
    a("#   哪个源真有这个文件、真实 URL、真实大小、**支不支持 Range 续传**。")
    a("# 有这张表就照表下单，按第 13 列的源顺序取。")
    a("#")
    a("# 第 13 列形如 ms:1,hf:0 —— 冒号后是探测时拿到的 Range 能力：")
    a("#   1 = 该源返回 206，可以 curl -C - 续传；0 = 返回 200 全量，续传位记 0。")
    a("# Range 位 0 的源上跑 curl -C - 会静默把目标文件从 0 重写，日志不报错。")
    a("# 源顺序固定为「Range 位 1 的排前面，Range 位 0 的排在最后、已有进度时直接跳过」。")
    a("MODELS=(")
    for m in models:
        note = (m.get("note") or "").replace("|", "/").replace('"', "'")
        row = "|".join([
            m["id"], m["repo"], m.get("ms_repo") or "", m["path"], m["target_dir"],
            m["target_name"] or os.path.basename(m["path"]),
            str(m["min_bytes"]), "1" if m.get("optional") else "0", m["group"], note,
            m.get("source_url") or "", str(m.get("source_bytes") or 0), src_order(m),
        ]).replace("$", "\\$").replace("`", "\\`")
        a(f'  "{row}"')
    a(")")
    a("")
    a('NEED=0')
    a('for row in "${MODELS[@]}"; do')
    a('  IFS="|" read -r id repo msrepo path tdir tname minb opt grp note <<<"$row"')
    a('  [ "$opt" = "1" ] && continue')
    a('  NEED=$((NEED + minb))')
    a("done")
    a('NEED=$((NEED * 12 / 10))')
    a('AVAIL=$(df -PB1 "$MODELS_DIR" 2>/dev/null | tail -n1 | awk "{print \\$4}")')
    a('AVAIL=${AVAIL:-0}')
