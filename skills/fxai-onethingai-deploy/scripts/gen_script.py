        a("# 下载一律用 curl + Range 续传，直接写到目标文件，**不在下载时做任何探测请求**。")
        a("#")
        a("# 为什么敢直接 -o 到目标文件：默认的源（`probe` 直链 / 魔搭 / HF）**都已提前探测过支持 Range**")
        a("# （probe_sources.py 跑一次就把「有没有这个文件 / 真实大小 / 支不支持续传」全问清楚了，")
        a("# 结果固化在 assets/models.json 的 source / source_url / source_bytes 里）。")
        a("# 下载时照着这张表下单即可，没必要再为每个文件发 HEAD 问一遍。")
        a("#")
        a("# ⚠️ 但这条路有个前提：源必须真的支持 Range。反面教材（仙宫云镜像）带 Range 请求会返回")
        a("#    200 全量而非 206，curl -C - 就会**静默把目标文件从 0 截断重写** —— 文件一夜之间")
        a("#    从 6.4 GB 回到 2 MB，日志里却不报错，只是「进度倒退」。")
        a("#    所以：**新增任何下载源之前，先跑 probe_sources.py 确认它返回 206**。")
        a("#")
        a("# $1=url  $2=目标文件")
        # ⚠️ curl 的 `--retry` 在**重试时会把 -o 的目标文件删掉重来**，
        # 而 `--retry-all-errors` 配 `-C -` 时，若每次尝试都没收到任何字节，
        # 已下载到几十 GB 的目标文件会被 curl 删掉重写，日志只留一行「失败（0 字节）」。
        # 硬链接快照：同分区 ln 只是加一个目录项，不占额外空间，
        # curl 删的是 out 这个名字，out.otaiprev 手上的那份 inode 安然无恙。
        a("grab_file() {")
        a('  local url="$1" out="$2"')
        a('  [ -n "$HAVE_CURL" ] || return 1')
        a('  local bak=""')
        a('  if [ -s "$out" ]; then')
        a('    bak="${out}.otaiprev"')
        a('    rm -f "$bak"')
        a('    ln "$out" "$bak" 2>/dev/null || cp -p "$out" "$bak" || true')
        a("  fi")
        a('  # 魔搭偶发 5xx/限流会让整段重来，重试放宽一点比重跑整个文件划算。')
        a('  curl -L -C - --retry 6 --retry-delay 3 --retry-all-errors \\')
        a('       --connect-timeout 30 --speed-time 60 --speed-limit 1024 \\')
        a('       -o "$out" "$url" 2>/dev/null || true')
        a('  # 下空了就把快照捞回来。宁可让它占着，也保住几十 GB 已下进度。')
        a('  if [ ! -s "$out" ] && [ -s "$bak" ]; then')
        a('    mv -f "$bak" "$out"')
        a('    log "      $out 上次下到一半被 curl 重试清掉了，已从快照还原（可能只剩部分）"')
        a("  fi")
        a("  return 0")
        a("}")
        a("grab_dir() {")
        a('  grab_file "$1" "$2/$(basename "$1")"')
        a("}")
        a("")
        a("# 下载源顺序。probe = probe_sources.py **提前探测过**的验证直链（最优先）。")
        a("# 流程是「先探测 → 拿到验证过的地址 → 再下载」。")
        a("# hf.x-gpu.com 镜像对本包模型返回 text/html 错误页，不是模型文件，默认排在最后。")
        a('# 想强制某顺序：export XGY_SRC_ORDER="ms,hf"')
        a('SRC_ORDER="${XGY_SRC_ORDER:-probe,ms,hf}"')
        a('log "下载源顺序：$SRC_ORDER"')
        a("")
        a("# 源名 -> URL。魔搭默认分支是 master（不是 main）；")
        a("# ms_repo 没显式配就沿用 HF 仓库 ID —— Comfy-Org / Kijai 这类在魔搭上基本同名。")
        a("src_url() {")
        a('  case "$1" in')
        a('    probe)  [ -n "$furl" ] && echo "$furl";;')
        a('    mirror) [ -n "$MIRROR" ]  && echo "$MIRROR/$repo/resolve/main/$path";;')
        a('    hf)     [ -n "$FALLBACK" ] && echo "$FALLBACK/$repo/resolve/main/$path";;')
        a('    ms)     [ -n "$MIRROR2" ] && echo "$MIRROR2/${msrepo:-$repo}/resolve/master/$path";;')
        a("    *) return 1;;")
        a("  esac")
        a("}")
        a("src_label() {")
        a('  case "$1" in')
        a('    probe) echo "探测直链";; mirror) echo "仙宫云镜像";; hf) echo "HF 官方";; ms) echo "魔搭";; *) echo "$1";;')
        a("  esac")
        a("}")
        a("# 断点续传能力是**站点级**的属性：一个站要么整体支持 Range，要么整体不支持，")
        a("# 没必要每个模型探一遍。值直接来自 models.json 的 resume 段：")
        a("#   魔搭     支持 Range，可续传")
        a("#   HF 官方  续传返 200 全量，curl 静默把目标文件从 0 重写")
        a("#   镜像     返回的是 HTML 首页，不是文件")
        a("resume_ok() {")
        a('  case "$1" in')
        a('    probe|ms) [ "${RESUME_MS:-1}" = "1" ];;')
        a('    hf)       [ "${RESUME_HF:-0}" = "1" ];;')
        a('    mirror)   [ "${RESUME_MIRROR:-0}" = "1" ];;')
        a('    *)        return 0;;')
        a("  esac")
        a("}")
        a("")
        a("dl_one() {")
        a('  local id="$1" repo="$2" msrepo="$3" path="$4" tdir="$5" tname="$6" minb="$7" note="${10}"')
        a('  local furl="${11:-}" fbytes="${12:-0}"   # probe_sources.py 探测出来的验证直链 + 真实字节')
        a('  local srcs="${13:-probe,ms,hf}"  # 这个模型的源顺序：源名:能否续传，探测阶段定好的')
        a('  local dest_dir="$MODELS_DIR/$tdir"')
        a('  local dest="$dest_dir/$tname"')
        a('  local base; base=$(basename "$path")')
        a('  local staged=""')
        a('  [ "$base" = "$tname" ] || staged="$dest_dir/.otai/$base"')
        a('  mkdir -p "$dest_dir/.otai"')
        a('  local have=0; [ -f "$dest" ] && have=$(stat -c%s "$dest" 2>/dev/null || echo 0)')
        a('  # 比真实大小还大 = 坏了：多个源按错偏移拼接会写出超长文件')
        a('  # （多源按错偏移拼接会写出超长文件）。留着会被下面判成「已存在」跳过，')
        a('  # 永远错下去 —— 直接删了重下。')
        a('  if [ "${fbytes:-0}" -gt 0 ] && [ "$have" -gt "$fbytes" ]; then')
        a('    log "残缺  $tname（$have > 真实 $fbytes，错偏移拼过），删掉重下"')
        a('    rm -f "$dest"')
        a('    have=0')
        a('  fi')
        a('  # 「已经下好了」的判据要用**真实大小** fbytes（min_bytes 是清单下限，比真实值小）。')
        a('  # min_bytes 是清单里的体积下限，比真实值小一截；用它判定会让差几百 MB 的文件')
        a('  # 被判「已存在」直接跳过，永远补不上最后那一段。')
        a('  local want0="$fbytes"; [ "${want0:-0}" -gt 0 ] || want0="$minb"')
        a('  if [ "$have" -ge "$want0" ]; then')
        a('    log "跳过  $tname（已存在 $have 字节）"')
        a('    mark "$SKIP_FILE" "$tname"; return 0')
        a("  fi")
        a('  log "下载  $tname  ←  $repo/$path"')
        a('  [ -n "$note" ] && log "      （$note）"')
        a('  local used="" usedname="" s url target')
        a('  local first=1 first_url="" tsize=0')
        a('  # 逗号分隔的源名逐个试：只要这个源没能把文件拿完整，就换下一个接着续。')
        a('  # 关键：判据是**体积**，不是「有没有拿到字节」。')
        a('  # 半截 safetensors 的文件头是合法的，只看文件头会在第一个源就 break，')
        a('  # 后面两个源根本没机会补齐 —— 判据一律用体积。')
        a('  local IFS_OLD="$IFS"; IFS=","')
        a('  local last_url=""')
        a('  for ent in $srcs; do')
        a('    IFS="$IFS_OLD"')
        a('    # 每项形如 ms:1 —— 冒号后是探测时量到的 Range 能力，不会到时候再去猜')
        a('    case "$ent" in')
        a('      *:*) s="${ent%%:*}"; rflag="${ent##*:}";;')
        a('      *)   s="$ent"; rflag="1";;')
        a('    esac')
        a('    url=$(src_url "$s") || { IFS=","; continue; }')
        a('    IFS=","')
        a('    [ -n "$url" ] || continue')
        a('    # probe 直链往往就是某个通用源的 URL（探测时最常选中的就是魔搭）。')
        a('    # 这时再「换源」过去等于拿同一个 URL 原地重试，纯属浪费一轮 —— 去重跳过。')
        a('    [ "$url" = "$last_url" ] && continue')
        a('    if [ -n "$staged" ]; then target="$staged"; else target="$dest"; fi')
        a('    # Range 位 0 的源：本地只要已经有字节，就跳过它，让它碰不到这个文件。')
        a('    # curl -C - 撞上它不会报错，只会把目标文件从 0 重写，日志无异常；')
        a('    # 宁可跳过，等下一轮能续传的源接着补齐。')
        a('    if [ "$rflag" = "0" ] || ! resume_ok "$s"; then')
        a('      local cur=0; [ -f "$target" ] && cur=$(stat -c%s "$target" 2>/dev/null || echo 0)')
        a('      if [ "$cur" -gt 0 ]; then')
        a('        # 已有进度、但这一站 Range 位0：原文件留着不动，先单独下到临时文件，')
        a('        # 只有「下载结果比现在更大」才采纳。这样既不丢进度，也不会永久卡住。')
        a('        local part="$target.otaipart"')
        a('        rm -f "$part"')
        a('        log "      $tname：$(src_label "$s") 不支持续传，先下临时文件（现有 $cur 字节留着）"')
        a('        grab_file "$url" "$part"')
        a('        local pn=0; [ -s "$part" ] && pn=$(stat -c%s "$part" 2>/dev/null || echo 0)')
        a('        if [ "$pn" -gt "$cur" ] && looks_like_model "$part"; then')
        a('          mv -f "$part" "$target"')
        a('        else')
        a('          rm -f "$part"')
        a('          log "      $tname：$(src_label "$s") 这次只拿到 $pn 字节，不采纳"')
        a('          continue')
        a('        fi')
        a('      fi')
        a('    fi')
        a('    last_url="$url"')
        a('    [ -n "$first_url" ] || first_url="$url"')
        a('    # 带上 $tname：并发下载时好几个模型的日志交错在一起，光看「换源」根本不知道是谁在换')
        a('    [ "$first" = "1" ] || log "      $tname 换源：$(src_label "$s")（保留已下部分，接着续）"')
        a('    first=0')
        a('    # 期望大小：表里每个候选源都带了探测时量好的字节数（$fbytes 是首选源那份）。')
        a('    if [ "${fbytes:-0}" -gt 0 ]; then tsize="$fbytes"; else tsize=$(remote_size "$url"); fi')
        a('    grab_file "$url" "$target"')
        a('    [ -s "$target" ] || continue')
        a('    if ! looks_like_model "$target"; then')
        a('      # 文件头就不对 → 404 的 JSON / HTML 错误页，清掉换下一个源')
        a('      rm -f "$target"')
        a("      continue")
        a("    fi")
        a('    # 文件头合法：体积达标就是成功，没达标就换源续传（不删！前面几个 G 要留着）')
        a('    local g; g=$(stat -c%s "$target" 2>/dev/null || echo 0)')
        a('    if [ "$g" -ge "$minb" ] && { [ "$tsize" -le 0 ] || [ "$g" -eq "$tsize" ]; }; then')
        a('      used="$url"; usedname="$s"; break')
        a("    fi")
        a('    [ "$tsize" -gt 0 ] && log "      $tname 在 $(src_label "$s") 只到 $g/$tsize，继续换源 ..."')
        a("  done")
        a('  IFS="$IFS_OLD"')
        a('  [ -z "$used" ] && err "所有源都试过了，$tname 仍未拿完整（试过 $srcs）"')
        a('  [ -n "$staged" ] && [ -s "$staged" ] && mv -f "$staged" "$dest"')
        a('  [ -n "$usedname" ] && log "      来源：$(src_label "$usedname")"')
        a('  local got=0; [ -f "$dest" ] && got=$(stat -c%s "$dest" 2>/dev/null || echo 0)')
        a('  # ⚠️ 失败也**绝不得删**目标文件：curl -C - 下次能从这里接着下。')
        a('  # 失败只标记、不删目标文件：删掉就丢掉已下到的几十 GB 进度。')
        a('  if [ "$got" -le 0 ]; then')
        a('    err "失败（0 字节）：$tname —— 保留现有文件，重跑即可续传"')
        a('    mark "$BAD_FILE" "$tname"; return 1')
        a("  fi")
        a('  if ! looks_like_model "$dest"; then')
        a('    err "文件头不像模型（多半是错误页）：$tname"')
        a('    head -c 80 "$dest" 2>/dev/null | tr -d "\\0-\\10\\13\\34\\40-\\176" | head -c 80 | sed "s/^/      /"')
        a('    rm -f "$dest"; mark "$BAD_FILE" "$tname"; return 1')
        a("  fi")
        a("  # 源循环已经逐个试过了，正常到这里体积应该已经对上。")
        a("  # 仍不一致（某源只续到一部分）就再补续传一轮。")
        a("  # 期望大小优先用**探测时已经量好**的 fbytes，省一次 HEAD 往返；")
        a("  # 只有没探测过（走了兜底源）才临时去问一次。")
        a('  local want="$fbytes"')
        a('  [ "$want" -gt 0 ] || want=$(remote_size "${used:-$first_url}")')
        a('  if [ "$want" -gt 0 ] && [ "$got" -ne "$want" ]; then')
        a('    log "      体积不符（本地 $got / 远端 $want），兜底续传一轮 ..."')
        a('    local e2 s2 u2 r2')
        a('    local IFS_OLD2="$IFS"; IFS=","')
        a('    for e2 in $srcs; do')
        a('      IFS="$IFS_OLD2"')
        a('      [ "$got" -ge "$want" ] && break')
        a('      case "$e2" in *:*) s2="${e2%%:*}"; r2="${e2##*:}";; *) s2="$e2"; r2="1";; esac')
        a('      u2=$(src_url "$s2") || { IFS=","; continue; }')
        a('      IFS=","')
        a('      [ -n "$u2" ] || continue')
        a('      # 这里手里已经有一部分了，Range 位 0 的源一律跳过（理由同上）')
        a('      { [ "$r2" = "0" ] || ! resume_ok "$s2"; } && continue')
        a('      grab_file "$u2" "$dest"')
        a('      got=$(stat -c%s "$dest" 2>/dev/null || echo 0)')
        a('      [ "$got" -ge "$want" ] && log "      已由 $(src_label "$s2") 补齐"')
        a("    done")
        a('    IFS="$IFS_OLD2"')
        a("  fi")
        a('  if [ "$got" -lt "$minb" ]; then')
        a('    err "体积不足（$got < $minb）：$tname"')
        a('    # 别删！半截文件留着，下次重跑 curl -C - 能接着下。')
        a('    # 只有「明显不是模型」才清（错误页），否则等于把几个 G 的进度白扔。')
        a('    looks_like_model "$dest" || rm -f "$dest"')
        a('    mark "$BAD_FILE" "$tname"; return 1')
        a("  fi")
        a('  log "完成  $tname（$got 字节）"')
        a('  mark "$OK_FILE" "$tname"')
        a("  return 0")
        a("}")
