    a("#  幂等：已存在且体积达标的文件会跳过；中断后重跑即可续上。")
    a("# ============================================================")
    a("set -uo pipefail")
    a("")
    a(f'MIRROR="${{XGY_MIRROR:-{mf["mirror"]}}}"')
